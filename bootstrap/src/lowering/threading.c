#include "project_internal.h"

/* One small adapter is embedded only in programs using concurrency intrinsics.
 * libuv layouts and callbacks never become Mini's public type representation. */
void mini_puv_runtime(Context *c, Buffer *out) {
    if (!c->result.requires_libuv)
        return;
    mini_pwrite(
        c, out, "%s",
        "#define MINI_USES_LIBUV 1\n#include <uv.h>\n#include <stdatomic.h>\n"
        "typedef struct { uv_thread_t id; void* payload; void (*run)(void*); atomic_bool done; } "
        "mini_uv_thread;\n"
        "static void mini_uv_entry(void* data) { mini_uv_thread* t=data; t->run(t->payload); "
        "atomic_store_explicit(&t->done,true,memory_order_release); }\n"
        "static uint8_t* mini_uv_start(const void* task,size_t bytes,void (*run)(void*),int32_t* "
        "error) {\n"
        "*error=0; mini_uv_thread* t=malloc(sizeof(*t)); if(!t) { *error=UV_ENOMEM; return NULL; "
        "}\n"
        "t->payload=malloc(bytes); if(!t->payload) { free(t); *error=UV_ENOMEM; return NULL; }\n"
        "memcpy(t->payload,task,bytes); t->run=run; atomic_init(&t->done,false);\n"
        "int code=uv_thread_create(&t->id,mini_uv_entry,t); if(code) { free(t->payload); free(t); "
        "*error=code; return NULL; }\n"
        "return (uint8_t*)t; }\n"
        "static int32_t mini_uv_join(uint8_t* handle) { mini_uv_thread* "
        "t=(mini_uv_thread*)handle;\n"
        "uv_thread_t current=uv_thread_self(); if(uv_thread_equal(&current,&t->id)) return "
        "UV_EBUSY;\n"
        "int code=uv_thread_join(&t->id); if(code) return code; free(t->payload); free(t); return "
        "0; }\n"
        "static bool mini_uv_alive(uint8_t* handle) { mini_uv_thread* t=(mini_uv_thread*)handle; "
        "return !atomic_load_explicit(&t->done,memory_order_acquire); }\n"
        "static void mini_uv_sleep(uintptr_t milliseconds) { while(milliseconds>UINT_MAX) { "
        "uv_sleep(UINT_MAX); milliseconds-=UINT_MAX; } uv_sleep((unsigned int)milliseconds); }\n"
        "typedef struct { uv_mutex_t gate; uv_cond_t ready; bool held; size_t waiters; uv_thread_t "
        "owner; } "
        "mini_uv_mutex;\n"
        "static uint8_t* mini_uv_mutex_create(int32_t* error) {\n"
        "    *error=0; mini_uv_mutex* m=malloc(sizeof(*m));\n"
        "    if(!m) { *error=UV_ENOMEM; return NULL; }\n"
        "    int code=uv_mutex_init(&m->gate);\n"
        "    if(code) { free(m); *error=code; return NULL; }\n"
        "    code=uv_cond_init(&m->ready);\n"
        "    if(code) { uv_mutex_destroy(&m->gate); free(m); *error=code; return NULL; }\n"
        "    m->held=false; m->waiters=0; return (uint8_t*)m;\n"
        "}\n"
        "static int32_t mini_uv_mutex_lock(uint8_t* memory) {\n"
        "    mini_uv_mutex* m=(mini_uv_mutex*)memory; uv_thread_t self=uv_thread_self();\n"
        "    uv_mutex_lock(&m->gate);\n"
        "    if(m->held && uv_thread_equal(&m->owner,&self)) { uv_mutex_unlock(&m->gate); return "
        "UV_EBUSY; }\n"
        "    while(m->held) { m->waiters++; uv_cond_wait(&m->ready,&m->gate); m->waiters--; }\n"
        "    m->owner=self; m->held=true; uv_mutex_unlock(&m->gate); return 0;\n"
        "}\n"
        "static int32_t mini_uv_mutex_trylock(uint8_t* memory) {\n"
        "    mini_uv_mutex* m=(mini_uv_mutex*)memory; uv_mutex_lock(&m->gate);\n"
        "    if(m->held) { uv_mutex_unlock(&m->gate); return UV_EBUSY; }\n"
        "    m->owner=uv_thread_self(); m->held=true; uv_mutex_unlock(&m->gate); return 0;\n"
        "}\n"
        "static int32_t mini_uv_mutex_unlock(uint8_t* memory) {\n"
        "    mini_uv_mutex* m=(mini_uv_mutex*)memory; uv_thread_t self=uv_thread_self();\n"
        "    uv_mutex_lock(&m->gate);\n"
        "    if(!m->held || !uv_thread_equal(&m->owner,&self)) { uv_mutex_unlock(&m->gate); return "
        "UV_EPERM; }\n"
        "    m->held=false; uv_cond_signal(&m->ready); uv_mutex_unlock(&m->gate); return 0;\n"
        "}\n"
        "static int32_t mini_uv_mutex_close(uint8_t* memory) {\n"
        "    mini_uv_mutex* m=(mini_uv_mutex*)memory;\n"
        "    int code=uv_mutex_trylock(&m->gate); if(code) return code;\n"
        "    if(m->held || m->waiters) { uv_mutex_unlock(&m->gate); return UV_EBUSY; }\n"
        "    uv_mutex_unlock(&m->gate); uv_cond_destroy(&m->ready); uv_mutex_destroy(&m->gate); "
        "free(m); return 0;\n"
        "}\n"
        "static int32_t mini_uv_oom(void) { return UV_ENOMEM; }\n"
        "static int32_t mini_uv_busy(void) { return UV_EBUSY; }\n"
        "static int32_t mini_uv_refused(void) { return UV_ECONNREFUSED; }\n"
        "static int32_t mini_uv_reset(void) { return UV_ECONNRESET; }\n"
        /* Blocking TCP: each connection/listener drives its own loop until the operation ends. */
        "typedef struct { uv_loop_t* loop; bool own; uv_tcp_t tcp; uint8_t* rbuf; size_t rcap; "
        "ssize_t result; bool done; } mini_uv_tcp;\n"
        "typedef struct { uv_loop_t* loop; uv_tcp_t tcp; mini_uv_tcp* pending; int status; bool "
        "done; } mini_uv_listener;\n"
        "static void mini_uv_noop_close(uv_handle_t* h) { (void)h; }\n"
        "static void mini_uv_flag_close(uv_handle_t* h) { *(bool*)h->data=true; }\n"
        "static mini_uv_tcp* mini_uv_tcp_new(uv_loop_t* loop, bool own, int32_t* error) {\n"
        "    mini_uv_tcp* c=calloc(1,sizeof(*c)); if(!c) { *error=UV_ENOMEM; return NULL; }\n"
        "    c->loop=loop; c->own=own; int code=uv_tcp_init(loop,&c->tcp);\n"
        "    if(code) { free(c); *error=code; return NULL; }\n"
        "    c->tcp.data=c; return c;\n"
        "}\n"
        "static uv_loop_t* mini_uv_loop_new(int32_t* error) {\n"
        "    uv_loop_t* l=malloc(sizeof(*l)); if(!l) { *error=UV_ENOMEM; return NULL; }\n"
        "    int code=uv_loop_init(l); if(code) { free(l); *error=code; return NULL; }\n"
        "    return l;\n"
        "}\n"
        "static void mini_uv_tcp_destroy(mini_uv_tcp* c) {\n"
        "    bool closed=false; c->tcp.data=&closed; uv_close((uv_handle_t*)&c->tcp,"
        "mini_uv_flag_close);\n"
        "    while(!closed) uv_run(c->loop,UV_RUN_ONCE);\n"
        "    if(c->own) { uv_loop_close(c->loop); free(c->loop); } free(c);\n"
        "}\n"
        "static void mini_uv_connected(uv_connect_t* req,int status) {\n"
        "    mini_uv_tcp* c=req->handle->data; c->result=status; c->done=true; uv_stop(c->loop);\n"
        "}\n"
        "static uint8_t* mini_uv_tcp_connect(uint8_t* host,int32_t port,int32_t* error) {\n"
        "    *error=0; struct sockaddr_in addr; int code=uv_ip4_addr((const char*)host,port,&addr);\n"
        "    if(code) { *error=code; return NULL; }\n"
        "    uv_loop_t* loop=mini_uv_loop_new(error); if(!loop) return NULL;\n"
        "    mini_uv_tcp* c=mini_uv_tcp_new(loop,true,error);\n"
        "    if(!c) { uv_loop_close(loop); free(loop); return NULL; }\n"
        "    uv_connect_t req; code=uv_tcp_connect(&req,&c->tcp,(const struct sockaddr*)&addr,"
        "mini_uv_connected);\n"
        "    if(!code) { uv_run(loop,UV_RUN_DEFAULT); code=(int)c->result; }\n"
        "    if(code) { *error=code; mini_uv_tcp_destroy(c); return NULL; }\n"
        "    return (uint8_t*)c;\n"
        "}\n"
        "static void mini_uv_incoming(uv_stream_t* server,int status) {\n"
        "    mini_uv_listener* l=server->data; if(l->done) return;\n"
        "    l->status=status; l->done=true;\n"
        "    if(!status) { int code=uv_accept(server,(uv_stream_t*)&l->pending->tcp); if(code) "
        "l->status=code; }\n"
        "    uv_stop(l->loop);\n"
        "}\n"
        "static uint8_t* mini_uv_tcp_listen(int32_t port,int32_t* error) {\n"
        "    *error=0; struct sockaddr_in addr; int code=uv_ip4_addr(\"127.0.0.1\",port,&addr);\n"
        "    if(code) { *error=code; return NULL; }\n"
        "    mini_uv_listener* l=calloc(1,sizeof(*l)); if(!l) { *error=UV_ENOMEM; return NULL; }\n"
        "    l->loop=mini_uv_loop_new(error); if(!l->loop) { free(l); return NULL; }\n"
        "    code=uv_tcp_init(l->loop,&l->tcp);\n"
        "    if(!code) { l->tcp.data=l; code=uv_tcp_bind(&l->tcp,(const struct sockaddr*)&addr,0); "
        "if(!code) code=uv_listen((uv_stream_t*)&l->tcp,128,mini_uv_incoming); }\n"
        "    if(code) {\n"
        "        *error=code; uv_close((uv_handle_t*)&l->tcp,mini_uv_noop_close); "
        "uv_run(l->loop,UV_RUN_DEFAULT);\n"
        "        uv_loop_close(l->loop); free(l->loop); free(l); return NULL;\n"
        "    }\n"
        "    return (uint8_t*)l;\n"
        "}\n"
        "static uint8_t* mini_uv_tcp_accept(uint8_t* handle,int32_t* error) {\n"
        "    *error=0; mini_uv_listener* l=(mini_uv_listener*)handle;\n"
        "    mini_uv_tcp* c=mini_uv_tcp_new(l->loop,false,error); if(!c) return NULL;\n"
        "    l->pending=c; l->done=false; l->status=0; uv_run(l->loop,UV_RUN_DEFAULT);\n"
        "    l->pending=NULL;\n"
        "    if(l->status) { *error=l->status; mini_uv_tcp_destroy(c); return NULL; }\n"
        "    return (uint8_t*)c;\n"
        "}\n"
        "static void mini_uv_wrote(uv_write_t* req,int status) {\n"
        "    mini_uv_tcp* c=req->handle->data; c->result=status; c->done=true; uv_stop(c->loop);\n"
        "}\n"
        "static intptr_t mini_uv_tcp_write(uint8_t* handle,uint8_t* data,uintptr_t len) {\n"
        "    mini_uv_tcp* c=(mini_uv_tcp*)handle; if(!len) return 0;\n"
        "    uv_buf_t buf=uv_buf_init((char*)data,(unsigned int)len); uv_write_t req;\n"
        "    if(len>UINT_MAX) return UV_E2BIG;\n"
        "    c->done=false; int code=uv_write(&req,(uv_stream_t*)&c->tcp,&buf,1,mini_uv_wrote);\n"
        "    if(code) return code;\n"
        "    uv_run(c->loop,UV_RUN_DEFAULT);\n"
        "    return c->result<0 ? (intptr_t)c->result : (intptr_t)len;\n"
        "}\n"
        "static void mini_uv_alloc(uv_handle_t* h,size_t suggested,uv_buf_t* buf) {\n"
        "    mini_uv_tcp* c=h->data; (void)suggested; *buf=uv_buf_init((char*)c->rbuf,"
        "(unsigned int)(c->rcap>UINT_MAX?UINT_MAX:c->rcap));\n"
        "}\n"
        "static void mini_uv_readable(uv_stream_t* s,ssize_t n,const uv_buf_t* buf) {\n"
        "    mini_uv_tcp* c=s->data; (void)buf; if(n==0) return;\n"
        "    c->result=(n==UV_EOF)?0:n; c->done=true; uv_read_stop(s); uv_stop(c->loop);\n"
        "}\n"
        "static intptr_t mini_uv_tcp_read(uint8_t* handle,uint8_t* buf,uintptr_t cap) {\n"
        "    mini_uv_tcp* c=(mini_uv_tcp*)handle; if(!cap) return 0;\n"
        "    c->rbuf=buf; c->rcap=cap; c->done=false; c->result=0;\n"
        "    int code=uv_read_start((uv_stream_t*)&c->tcp,mini_uv_alloc,mini_uv_readable);\n"
        "    if(code) return code;\n"
        "    uv_run(c->loop,UV_RUN_DEFAULT);\n"
        "    return (intptr_t)c->result;\n"
        "}\n"
        "static int32_t mini_uv_tcp_close(uint8_t* handle) {\n"
        "    mini_uv_tcp* c=(mini_uv_tcp*)handle; mini_uv_tcp_destroy(c); return 0;\n"
        "}\n"
        "static int32_t mini_uv_listener_close(uint8_t* handle) {\n"
        "    mini_uv_listener* l=(mini_uv_listener*)handle;\n"
        "    uv_close((uv_handle_t*)&l->tcp,mini_uv_noop_close); uv_run(l->loop,UV_RUN_DEFAULT);\n"
        "    uv_loop_close(l->loop); free(l->loop); free(l); return 0;\n"
        "}\n");
}
void mini_puv_bridge(Context *c, Buffer *out) {
    if (!c->uv_task_type)
        return;
    mini_pwrite(c, out,
                "static void mini_uv_run_task(void* task) { mini_invoke_%zu(*(%s*)task); }\n",
                c->uv_task_type->id, mini_pctype(c, c->uv_task_type));
}
