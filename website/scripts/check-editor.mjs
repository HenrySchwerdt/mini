import assert from 'node:assert/strict'

/** Exercise real keyboard events, not just CodeMirror commands dispatched by a test. */
export async function checkEditor(page, editor) {
  const text = async () => (await editor.locator('.cm-line').allTextContents()).join('\n')
  await editor.fill('')
  await editor.pressSequentially('fun main() {')
  assert.equal(await text(), 'fun main() {}', 'brackets close while typing')
  await editor.press('Enter')
  assert.equal(await text(), 'fun main() {\n    \n}', 'Enter creates a four-space function body')
  await editor.pressSequentially('if (true) {')
  await editor.press('Enter')
  assert.equal(await text(), 'fun main() {\n    if (true) {\n        \n    }\n}', 'nested blocks indent and align closing braces')
  await editor.pressSequentially('println("hello")')
  await editor.press('Enter')
  assert.match(await text(), /println\("hello"\)\n        \n/, 'Enter preserves function-body indentation')
  await editor.press('}')
  assert.match(await text(), /println\("hello"\)\n    }/, 'closing brace dedents')

  await editor.fill('val count = 1\nval other = 2')
  await editor.press('ControlOrMeta+a')
  await editor.press('Tab')
  assert.equal(await text(), '    val count = 1\n    val other = 2', 'Tab shifts selected lines')
  await editor.press('Shift+Tab')
  assert.equal(await text(), 'val count = 1\nval other = 2', 'Shift+Tab reverses indentation')
  await editor.press('ArrowRight')
  await editor.press('ControlOrMeta+End')
  await editor.press('Enter')
  await editor.press('Tab')
  assert.match(await text(), /\n    $/, 'Tab inserts spaces at the cursor')
  await editor.press('Backspace')
  assert.match(await text(), /\n$/, 'Backspace removes an indentation level')

  await editor.fill('')
  await editor.pressSequentially('pri')
  await editor.press('Control+Space')
  const println = page.locator('.cm-tooltip-autocomplete [role="option"]').filter({ hasText: /^println/ }).first()
  await println.waitFor()
  await println.click()
  assert.equal(await text(), 'println(value)', 'completion inserts the Kotlin snippet')
  await page.keyboard.insertText('"hello"')
  await editor.press('Tab')
  await page.keyboard.insertText(' // done')
  assert.equal(await text(), 'println("hello") // done', 'Tab advances out of the snippet field')
  await editor.press('ControlOrMeta+z')
  assert.ok(!(await text()).endsWith(' // done'), 'undo restores the previous edit')

  await editor.fill('val reportCount = 3\nrep')
  await editor.press('ControlOrMeta+End')
  await editor.press('Control+Space')
  await page.locator('.cm-tooltip-autocomplete [role="option"]').filter({ hasText: /^reportCount$/ }).waitFor()
  await editor.press('Escape')
  await editor.fill('val count = 1')
  await editor.press('ControlOrMeta+/')
  assert.match(await text(), /^\/\/\s*val count = 1/, 'line comment shortcut works')
  await editor.press('ControlOrMeta+/')
  assert.equal(await text(), 'val count = 1')
  await editor.press('ControlOrMeta+f')
  const search = page.locator('.cm-search input[name="search"]')
  await search.waitFor()
  await search.fill('count')
  await page.locator('.cm-search input[name="replace"]').fill('total')
  await page.locator('.cm-search button[name="replaceAll"]').click()
  assert.equal(await text(), 'val total = 1', 'replace updates the document')
  await search.press('Escape')
  assert.equal(await page.locator('.cm-search').count(), 0, 'search closes with Escape')
  await editor.fill('val total = total + 1')
  await editor.press('ControlOrMeta+Home')
  for (let i = 0; i < 4; i++) await editor.press('ArrowRight')
  await editor.press('ControlOrMeta+d')
  await editor.press('ControlOrMeta+d')
  await page.keyboard.insertText('count')
  assert.equal(await text(), 'val count = count + 1', 'next-occurrence selection supports simultaneous edits')
}
