#!/usr/bin/env node
// Generates the diagnostics reference (website/reference/diagnostics/*.md) from the memory-model test corpus.
//
//   compiler/testdata/memory/NAME.kt    the program (header comment says REJECT/ACCEPT)
//   compiler/testdata/memory/NAME.diag  expected `line:col: CODE`
//
// For every code the script picks an example program (see "example" in diagnostics-meta.json, otherwise the
// smallest corpus file), RUNS THE REAL COMPILER (`./minic check`) on it, checks that the compiler reports
// the code at the position the corpus expects, and writes a page with the source, the compiler output
// and the hand-written explanation from diagnostics-meta.json.
//
// Usage: node website/scripts/gen-diagnostics.mjs     (needs JDK 21; ./minic builds the compiler on first use)
import { spawnSync } from 'node:child_process'
import { readFileSync, readdirSync, writeFileSync, mkdirSync, rmSync, existsSync } from 'node:fs'
import { dirname, join, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const root = resolve(here, '../..')
const corpusRel = 'compiler/testdata/memory'
const corpus = join(root, corpusRel)
const outDir = join(root, 'website/reference/diagnostics')
const meta = JSON.parse(readFileSync(join(here, 'diagnostics-meta.json'), 'utf8'))
const repoUrl = 'https://github.com/HenrySchwerdt/mini/blob/main'

const codes = Object.keys(meta).filter((k) => !k.startsWith('_')).sort()

// code -> [{ name, line, col }]
const corpusByCode = new Map()
for (const f of readdirSync(corpus).filter((f) => f.endsWith('.diag')).sort()) {
  const name = f.replace(/\.diag$/, '')
  for (const l of readFileSync(join(corpus, f), 'utf8').split('\n')) {
    const m = l.match(/^(\d+):(\d+): (M\d{4})/)
    if (m) {
      if (!corpusByCode.has(m[3])) corpusByCode.set(m[3], [])
      corpusByCode.get(m[3]).push({ name, line: +m[1], col: +m[2] })
    }
  }
}

function runMinic(args) {
  const r = spawnSync(join(root, 'minic'), args, { cwd: root, encoding: 'utf8' })
  if (r.error) throw r.error
  const clean = (s) =>
    s
      .split('\n')
      .filter((l) => !l.startsWith('Picked up JAVA_TOOL_OPTIONS'))
      .join('\n')
      .split(root + '/')
      .join('')
  return { status: r.status, stdout: clean(r.stdout), stderr: clean(r.stderr) }
}

function esc(s) {
  return s.replace(/\s+$/, '')
}

rmSync(outDir, { recursive: true, force: true })
mkdirSync(outDir, { recursive: true })

const problems = []
const rows = []

for (const code of codes) {
  const m = meta[code]
  const entries = corpusByCode.get(code) ?? []
  let page = `---\ntitle: ${JSON.stringify(code + " " + m.title)}\n---\n\n# ${code}: ${m.title}\n\n`
  page += `<span class="diag-badge ${m.severity}">${m.severity}</span>`
  if (m.status === 'planned') page += ` <span class="diag-badge planned">planned, not implemented</span>`
  page += `\n\n## What it means\n\n${m.meaning}\n\n`

  if (m.example) {
    const name = m.example
    const rel = `${corpusRel}/${name}.kt`
    const src = readFileSync(join(root, rel), 'utf8')
    const exp = entries.find((e) => e.name === name)
    if (!exp) problems.push(`${code}: example ${name} has no ${code} line in its .diag file`)
    const r = runMinic(['check', rel])
    const out = esc(r.stderr)
    const brief = runMinic(['check', '--brief', rel])
    const want = exp ? `${exp.line}:${exp.col}: ${code}` : ''
    if (exp && !brief.stdout.split('\n').includes(want)) {
      problems.push(`${code}: compiler did not report "${want}" for ${name} (got: ${brief.stdout.trim()})`)
    }
    if (!out.includes(`[${code}]`)) problems.push(`${code}: full output of ${name} does not mention ${code}`)
    const isWarning = m.severity === 'warning'
    page += `## Minimal failing example\n\n`
    page += `From the test corpus: [\`${rel}\`](${repoUrl}/${rel}). `
    page += `The corpus expects \`${want}\` (the \`^\` comment in the source marks the column).\n\n`
    page += '```kotlin check=' + (isWarning ? 'warn:' : '') + code + '\n' + esc(src) + '\n```\n\n'
    page += `## Compiler output\n\n`
    page += 'Generated by running `./minic check ' + rel + '`'
    page += isWarning ? ' (exit status 0: a warning does not fail the build).\n\n' : ` (exit status ${r.status}).\n\n`
    page += '```text\n$ ./minic check ' + rel + '\n' + out + '\n```\n\n'
  } else {
    page += `## Example\n\nThere is no example: this code is not emitted by the compiler yet, so there is no corpus program and no compiler output to show.\n\n`
  }

  page += `## How to fix\n\n${m.fix}\n\n`

  const others = entries.filter((e) => e.name !== m.example)
  if (entries.length) {
    page += `## Corpus programs for this code\n\n`
    page += entries
      .map((e) => `- [\`${e.name}.kt\`](${repoUrl}/${corpusRel}/${e.name}.kt) (${e.line}:${e.col})${e.name === m.example ? ', shown above' : ''}`)
      .join('\n')
    page += '\n\n'
  }
  page += `See also: [Diagnostics overview](./) and the [memory guide](/memory/).\n`
  writeFileSync(join(outDir, `${code}.md`), page)
  rows.push({ code, ...m, n: entries.length })
}

// Index page
let idx = `---\ntitle: Diagnostics reference\n---\n\n# Diagnostics reference\n\n`
idx += `Every memory-model diagnostic has a stable code. The **code** and the **primary source position** are stable; the message text, labels and \`help:\` line may change. `
idx += `Errors stop the build (exit status 1); warnings do not, unless you pass \`-Werror\`.\n\n`
idx += `The pages below are generated by \`website/scripts/gen-diagnostics.mjs\` from the test corpus \`${corpusRel}/\` and the output of the real compiler, so they cannot drift from the implementation. Only the prose is hand-written.\n\n`
idx += `| Code | Severity | Meaning | Corpus programs |\n|---|---|---|---|\n`
for (const r of rows) {
  const sev = r.status === 'planned' ? `${r.severity} (planned)` : r.severity
  idx += `| [${r.code}](./${r.code}) | ${sev} | ${r.title} | ${r.n} |\n`
}
idx += `\n## Output format\n\n\`\`\`text\n<severity>[<code>]: <message>\n  --> <file>:<line>:<col>   <label>\n   <line> | <source line>\n          | <caret under the primary position>\n  help: <text>\n\`\`\`\n\n`
idx += `With \`./minic check --brief file.kt\` the compiler prints only \`line:col: CODE\` lines on stdout; this is what the test corpus compares.\n`
writeFileSync(join(outDir, 'index.md'), idx)

// Sidebar fragment consumed by .vitepress/config.mts
const sidebar = [{ text: 'Overview', link: '/reference/diagnostics/' }].concat(
  rows.map((r) => ({ text: `${r.code} ${r.title}`, link: `/reference/diagnostics/${r.code}` }))
)
writeFileSync(join(here, '../.vitepress/diagnostics-sidebar.json'), JSON.stringify(sidebar, null, 2) + '\n')

if (problems.length) {
  console.error('Problems:\n  ' + problems.join('\n  '))
  process.exit(1)
}
console.log(`generated ${rows.length} diagnostic pages in website/reference/diagnostics`)
