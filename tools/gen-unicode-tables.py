#!/usr/bin/env python3
"""Generates stdlib/kotlin/text/UnicodeTables.kt: the Unicode data of the Char functions (general category, simple case mappings,
Other_Uppercase / Other_Lowercase and the full uppercase mappings of kotlin.text.String.uppercase) for the Basic Multilingual Plane,
from the unicodedata module of this Python (Unicode 15.1).
Run: python3 tools/gen-unicode-tables.py > stdlib/kotlin/text/UnicodeTables.kt"""
import unicodedata, textwrap

CODES = {'Cn': 0, 'Lu': 1, 'Ll': 2, 'Lt': 3, 'Lm': 4, 'Lo': 5, 'Mn': 6, 'Me': 7, 'Mc': 8, 'Nd': 9, 'Nl': 10, 'No': 11, 'Zs': 12,
         'Zl': 13, 'Zp': 14, 'Cc': 15, 'Cf': 16, 'Co': 18, 'Cs': 19, 'Pd': 20, 'Ps': 21, 'Pe': 22, 'Pc': 23, 'Po': 24, 'Sm': 25,
         'Sc': 26, 'Sk': 27, 'So': 28, 'Pi': 29, 'Pf': 30}
N = 0x10000


def category(c):
    return CODES[unicodedata.category(chr(c))]


def simple_upper(c):
    u = chr(c).upper()
    if len(u) == 1:
        return ord(u)
    t = chr(c).title()
    return ord(t) if len(t) == 1 and t != chr(c) else c


def simple_lower(c):
    if c == 0x130:
        return 0x69
    l = chr(c).lower()
    return ord(l) if len(l) == 1 else c


def runs(f):
    out = []
    prev = None
    for c in range(N):
        v = f(c)
        if v != prev:
            out.append((c, v))
            prev = v
    return out


def num(v):
    """An unsigned number as 5-bit groups, low group first, each one character '0' + group (+ 32 when another group follows)."""
    out = []
    while True:
        low = v & 31
        v >>= 5
        if v == 0:
            out.append(chr(48 + low))
            return ''.join(out)
        out.append(chr(48 + 32 + low))


def zigzag(v):
    return (v << 1) if v >= 0 else ((-v << 1) - 1)


def signed16(v):
    return v - 65536 if v >= 32768 else v


def chunks(s, width=118):
    parts = textwrap.wrap(s, width, break_long_words=True, break_on_hyphens=False, drop_whitespace=False)
    return ' +\n        '.join('"%s"' % p.replace('\\', '\\\\') for p in parts)


cat_runs = runs(category)
up_runs = runs(lambda c: (simple_upper(c) - c) & 0xFFFF)
lo_runs = runs(lambda c: (simple_lower(c) - c) & 0xFFFF)


def run_table(rs, value):
    """count, then per run: the distance from the previous start, then the value (a character for categories, else a signed number)"""
    out = [num(len(rs))]
    prev = 0
    for c, v in rs:
        out.append(num(c - prev))
        out.append(value(v))
        prev = c
    return ''.join(out)


cat_s = run_table(cat_runs, lambda v: chr(48 + v))
up_s = run_table(up_runs, lambda v: num(zigzag(signed16(v))))
lo_s = run_table(lo_runs, lambda v: num(zigzag(signed16(v))))


def ranges(pred):
    out = []
    start = None
    for c in range(N + 1):
        p = c < N and pred(c)
        if p and start is None:
            start = c
        if not p and start is not None:
            out.append((start, c - 1))
            start = None
    return out


other_upper = ranges(lambda c: chr(c).isupper() and unicodedata.category(chr(c)) != 'Lu')
other_lower = ranges(lambda c: chr(c).islower() and unicodedata.category(chr(c)) != 'Ll')
def range_table(rs):
    """count, then per range: the distance from the end of the previous range to its first character, and its length - 1"""
    out = [num(len(rs))]
    prev = 0
    for a, b in rs:
        out.append(num(a - prev))
        out.append(num(b - a))
        prev = b
    return ''.join(out)


ou_s = range_table(other_upper)
ol_s = range_table(other_lower)
full = []
for c in range(N):
    if unicodedata.category(chr(c)) == 'Cs':
        continue
    u = chr(c).upper()
    if len(u) > 1:
        full.append('%04X:%s' % (c, ' '.join('%04X' % ord(x) for x in u)))
full_s = ';'.join(full)

print('''/*
 * Generated by tools/gen-unicode-tables.py; do not edit by hand.
 * Unicode %s data of the Basic Multilingual Plane for kotlin.text.Char: the general category (the codes of java.lang.Character.getType),
 * the simple upper / lower case mappings (runs of a start and a delta), Other_Uppercase / Other_Lowercase and the full uppercase
 * mappings of String.uppercase(). Each table is a string of numbers (5-bit groups, one printable character each, see UnicodeData.kt) that
 * is decoded on first use; the numbers are distances between the starts of runs, so most of them take one or two characters.
 */
package kotlin.text

internal object UnicodeTables {
    /** count, runs of (distance from the previous start, category: one character, '0' + the code) */
    const val CATEGORIES: String =
        %s

    /** count, runs of (distance from the previous start, case mapping delta: zigzag) */
    const val UPPER: String =
        %s

    const val LOWER: String =
        %s

    /** count, ranges of (distance from the end of the previous range, length - 1) */
    const val OTHER_UPPER: String =
        %s

    const val OTHER_LOWER: String =
        %s

    /** `code:code code` entries separated by `;`, in hexadecimal */
    const val FULL_UPPER: String =
        %s
}''' % (unicodedata.unidata_version, chunks(cat_s), chunks(up_s), chunks(lo_s), chunks(ou_s), chunks(ol_s), chunks(full_s)))
