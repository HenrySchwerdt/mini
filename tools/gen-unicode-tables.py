#!/usr/bin/env python3
"""Generates stdlib/kotlin/text/UnicodeTables.kt: the Unicode data of the Char functions (general category, simple case mappings,
Other_Uppercase / Other_Lowercase and the full uppercase mappings of kotlin.text.String.uppercase) for the Basic Multilingual Plane,
from the unicodedata module of this Python (Unicode 15.1).
Run: python3 tools/gen-unicode-tables.py > stdlib/kotlin/text/UnicodeTables.kt"""
import unicodedata, textwrap

CODES = {'Cn': 0, 'Lu': 1, 'Ll': 2, 'Lt': 3, 'Lm': 4, 'Lo': 5, 'Mn': 6, 'Me': 7, 'Mc': 8, 'Nd': 9, 'Nl': 10, 'No': 11, 'Zs': 12,
         'Zl': 13, 'Zp': 14, 'Cc': 15, 'Cf': 16, 'Co': 18, 'Cs': 19, 'Pd': 20, 'Ps': 21, 'Pe': 22, 'Pc': 23, 'Po': 24, 'Sm': 25,
         'Sc': 26, 'Sk': 27, 'So': 28, 'Pi': 29, 'Pf': 30}
N = 0x10000


def category(c):
    return CODES[unicodedata.category(chr(c))]


def simple_upper(c):
    u = chr(c).upper()
    if len(u) == 1:
        return ord(u)
    t = chr(c).title()
    return ord(t) if len(t) == 1 and t != chr(c) else c


def simple_lower(c):
    if c == 0x130:
        return 0x69
    l = chr(c).lower()
    return ord(l) if len(l) == 1 else c


def runs(f):
    out = []
    prev = None
    for c in range(N):
        v = f(c)
        if v != prev:
            out.append((c, v))
            prev = v
    return out


def chunks(s, width=118):
    parts = textwrap.wrap(s, width, break_long_words=True, break_on_hyphens=False, drop_whitespace=False)
    return ' +\n        '.join('"%s"' % p for p in parts)


cat_runs = runs(category)
cat_s = ''.join('%04X%s' % (c, chr(ord('0') + v)) for c, v in cat_runs)
up_runs = runs(lambda c: (simple_upper(c) - c) & 0xFFFF)
lo_runs = runs(lambda c: (simple_lower(c) - c) & 0xFFFF)
up_s = ''.join('%04X%04X' % (c, v) for c, v in up_runs)
lo_s = ''.join('%04X%04X' % (c, v) for c, v in lo_runs)


def ranges(pred):
    out = []
    start = None
    for c in range(N + 1):
        p = c < N and pred(c)
        if p and start is None:
            start = c
        if not p and start is not None:
            out.append((start, c - 1))
            start = None
    return out


other_upper = ranges(lambda c: chr(c).isupper() and unicodedata.category(chr(c)) != 'Lu')
other_lower = ranges(lambda c: chr(c).islower() and unicodedata.category(chr(c)) != 'Ll')
ou_s = ''.join('%04X%04X' % r for r in other_upper)
ol_s = ''.join('%04X%04X' % r for r in other_lower)
full = []
for c in range(N):
    if unicodedata.category(chr(c)) == 'Cs':
        continue
    u = chr(c).upper()
    if len(u) > 1:
        full.append('%04X:%s' % (c, ' '.join('%04X' % ord(x) for x in u)))
full_s = ';'.join(full)

print('''/*
 * Generated by tools/gen-unicode-tables.py; do not edit by hand.
 * Unicode %s data of the Basic Multilingual Plane for kotlin.text.Char: the general category (the codes of java.lang.Character.getType),
 * the simple upper / lower case mappings (runs of a start and a delta), Other_Uppercase / Other_Lowercase and the full uppercase
 * mappings of String.uppercase(). Each table is a string of hexadecimal numbers that UnicodeData decodes on first use.
 */
package kotlin.text

internal object UnicodeTables {
    /** runs of (start: 4 hex digits, category: one character, '0' + the code) */
    const val CATEGORIES: String =
        %s

    /** runs of (start: 4 hex digits, delta: 4 hex digits, modulo 65536) */
    const val UPPER: String =
        %s

    const val LOWER: String =
        %s

    /** ranges of (first: 4 hex digits, last: 4 hex digits) */
    const val OTHER_UPPER: String =
        %s

    const val OTHER_LOWER: String =
        %s

    /** `code:code code` entries separated by `;` */
    const val FULL_UPPER: String =
        %s
}''' % (unicodedata.unidata_version, chunks(cat_s), chunks(up_s), chunks(lo_s), chunks(ou_s), chunks(ol_s), chunks(full_s)))
