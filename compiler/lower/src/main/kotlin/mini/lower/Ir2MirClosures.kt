/*
 * Ir2Mir: lambdas, function types, function references, local functions and captured variables.
 *
 * Function values are ordinary reference-counted objects.
 *  - A function type `(A, B) -> R` (also `A.(B) -> R`, KFunctionN) is the MIR interface
 *    `kotlin.FunctionN` with one method `invoke(Any?, ...) : Any?`. The uniform erased ABI means
 *    primitives are boxed (mk_box_*) when they cross a function-value call.
 *  - Every lambda / function reference gets its own class (MirClass) with one field per captured
 *    value, implementing that interface. Its dispose (generated by the emitter) releases the captures.
 *  - Captured `val`s are copied into the closure. Captured `var`s live in a heap cell (a "Ref"
 *    class with one field `value`); declaring function and closures share the cell.
 *  - Local functions are lambda-lifted: the C function takes the captured values as leading
 *    parameters and calls are direct. Using one as a value (`::local`) creates a closure object.
 */

internal class RefClass(val cName: String, val ctor: String, val type: TObject, val valueType: MirType)

internal class LiftedFn(val cName: String, val captured: List<IrValueDeclaration>)

internal class InlineReturn(val result: MirLocal?, val label: MirLabel, val finallyDepth: Int)

// ---- function types ----------------------------------------------------------------------------------

internal fun Ir2Mir.functionArity(t: Type): Int? {
    val n = t.classFqName ?: return null
    val rest = when {
        n.startsWith("kotlin.Function") -> n.removePrefix("kotlin.Function")
        n.startsWith(REFLECT_PKG + ".KFunction") -> n.removePrefix(REFLECT_PKG + ".KFunction")
        else -> return null
    }
    return rest.toIntOrNull()
}

/** The MIR interface type for `FunctionN`, creating it on first use. */
internal fun Ir2Mir.functionInterface(arity: Int): TObject = functionInterfaces.getOrPut(arity) {
    val cName = Mangling.className("kotlin", listOf("Function$arity"))
    extraClasses += MirClass("kotlin.Function$arity", cName, true, null, emptyList(), emptyList(), emptyList(), emptyList())
    TObject("kotlin.Function$arity", cName, false, true)
}

internal val invokeArgTypes = { n: Int -> List(n) { anyNullableStatic } }
private val anyNullableStatic = TObject("kotlin.Any", ANY_CNAME, true)

// ---- ref cells ----------------------------------------------------------------------------------------

internal fun Ir2Mir.refClassFor(t: MirType): RefClass = refClasses.getOrPut(t) {
    val cName = Mangling.className("mk", listOf("Ref" + Mangling.typeLetter(t)))
    val type = TObject("mk.Ref", cName, false)
    val ctorName = Mangling.constructor(cName, listOf(t))
    extraClasses += MirClass("mk.Ref", cName, false, null, listOf(MirField("value", t)), emptyList(), listOf(null, null, null), emptyList())
    val self = MirLocal(0, "this", type)
    val v = MirLocal(1, "value", t)
    extraFunctions += MirFunction(
        "mk.Ref.<init>", ctorName, listOf(self, v), TUnit,
        listOf(MirStmt.SetField(MirExpr.Local(self), cName, "value", t, MirExpr.Local(v))), cName,
    )
    RefClass(cName, ctorName, type, t)
}

internal fun zeroOf(t: MirType): MirExpr = when (t) {
    TInt -> MirExpr.IntConst(0)
    TLong -> MirExpr.LongConst(0)
    TBoolean -> MirExpr.BooleanConst(false)
    TDouble -> MirExpr.DoubleConst(0.0)
    TChar -> MirExpr.CharConst(0)
    TByte, TShort -> MirExpr.Convert(MirExpr.IntConst(0), t)
    TFloat -> MirExpr.Convert(MirExpr.DoubleConst(0.0), TFloat)
    else -> MirExpr.NullConst(t)
}

internal fun Ir2Mir.declType(d: IrValueDeclaration): MirType = mirType(d.type, d)

/** The type a captured value has inside a closure (the cell for boxed vars). */
internal fun Ir2Mir.capturedType(d: IrValueDeclaration): MirType =
    if (d in closure.boxed) refClassFor(declType(d)).type else declType(d)

// ---- per function state --------------------------------------------------------------------------------

internal class FnState(
    val locals: HashMap<Any, MirLocal>,
    val localCounter: Int,
    val currentFunction: IrFunction?,
    val currentReturn: MirType,
    val unitAsNull: Boolean,
    val finallyStack: ArrayList<IrExpression>,
    val strict: Boolean = false,
    val allocLevels: ArrayList<List<AllocRef>> = ArrayList(),
)

internal fun Ir2Mir.saveFn() = FnState(locals, localCounter, currentFunction, currentReturn, unitAsNull, finallyStack, currentStrict, allocLevels)

internal fun Ir2Mir.restoreFn(s: FnState) {
    locals = s.locals
    localCounter = s.localCounter
    currentFunction = s.currentFunction
    currentReturn = s.currentReturn
    unitAsNull = s.unitAsNull
    finallyStack = s.finallyStack
    currentStrict = s.strict
    allocLevels = s.allocLevels
}

internal inline fun <T> Ir2Mir.inFreshFunction(body: () -> T): T {
    val saved = saveFn()
    locals = HashMap()
    localCounter = 0
    finallyStack = ArrayList()
    currentStrict = false
    allocLevels = ArrayList()
    try {
        return body()
    } finally {
        restoreFn(saved)
    }
}

// ---- closures -------------------------------------------------------------------------------------------

/**
 * Creates the class of one closure. [capTypes] are the field types; [makeBody] fills the body of
 * `invoke` inside a fresh function context: it receives `this`, the `Any?` argument locals and the
 * locals holding the captured values, and appends statements (it must end with a return).
 * Returns the constructor C name and the class type.
 */
internal fun Ir2Mir.closureClass(
    hint: String,
    arity: Int,
    capTypes: List<MirType>,
    sam: SamTarget? = null,
    makeBody: (self: MirLocal, args: List<MirLocal>, caps: List<MirLocal>, out: MutableList<MirStmt>) -> Unit,
): Pair<String, TObject> {
    val iface = if (sam == null) functionInterface(arity) else null
    val argTypes: List<MirType> = sam?.argTypes ?: List(arity) { anyNullable }
    val retType: MirType = sam?.ret ?: anyNullable
    val n = lambdaCounter++
    val qualified = "$hint\$$n"
    val cName = Mangling.className("", listOf("\$closure$n"))
    val type = TObject(qualified, cName, false)
    val fields = capTypes.mapIndexed { i, t -> MirField("c$i", t) }
    // constructor
    val ctorName = Mangling.constructor(cName, capTypes)
    run {
        val self = MirLocal(0, "this", type)
        val ps = capTypes.mapIndexed { i, t -> MirLocal(i + 1, "c$i", t) }
        val body = ps.mapIndexed { i, p -> MirStmt.SetField(MirExpr.Local(self), cName, "c$i", capTypes[i], MirExpr.Local(p)) }
        extraFunctions += MirFunction("$qualified.<init>", ctorName, listOf(self) + ps, TUnit, body, cName)
    }
    // invoke
    val invokeName = Mangling.method(cName, sam?.method?.name ?: "invoke", argTypes)
    val fn = inFreshFunction {
        val self = MirLocal(localCounter++, "this", type)
        val args = List(arity) { MirLocal(localCounter++, "p$it", argTypes[it]) }
        val out = ArrayList<MirStmt>()
        val caps = capTypes.mapIndexed { i, t ->
            val l = MirLocal(localCounter++, "cap$i", t)
            out += MirStmt.Declare(l, MirExpr.FieldGet(MirExpr.Local(self), cName, "c$i", t))
            l
        }
        makeBody(self, args, caps, out)
        MirFunction("$qualified.invoke", invokeName, listOf(self) + args, retType, out)
    }
    extraFunctions += fn
    if (iface != null) {
        extraClasses += MirClass(
            qualified, cName, false, null, fields, listOf(iface.cName), listOf(null, null, null),
            listOf(MirItable(iface.cName, listOf(invokeName))),
        )
    } else {
        val ifaces = allInterfaces(sam!!.iface) + sam.iface
        extraClasses += MirClass(
            qualified, cName, false, null, fields, ifaces.map { info(it).cName }, listOf(null, null, null),
            ifaces.map { i ->
                MirItable(info(i).cName, interfaceMethods(i).map { m -> if (m === sam.method) invokeName else implName(if (hasBody(m)) m else null) })
            },
        )
    }
    return ctorName to type
}

internal fun Ir2Mir.convertBodyOf(f: IrFunction, ret: MirType, out: MutableList<MirStmt>) {
    when (val body = f.body) {
        is IrBlockBody -> for (s in body.statements) stmt(s, out)
        is IrExpressionBody -> {
            val e = body.expression
            if (ret == TUnit) stmt(e, out) else returnValue(e, out)
        }
        else -> unsupported(f, "function body")
    }
}

/** A lambda literal used as a value: allocate its closure object. */
internal fun Ir2Mir.lambdaValue(e: IrFunctionExpression, out: MutableList<MirStmt>, sam: SamTarget? = null): MirExpr {
    val fn = e.function
    if (fn in closure.inlinedLambdas) unsupported(e, "lambda passed to an inline function that cannot be expanded in place")
    val caps = closure.capturesOf(fn)
    val capTypes = caps.map { capturedType(it) }
    val arity = fn.parameters.size
    val ret = mirType(fn.returnType, fn)
    val (ctor, type) = closureClass(currentFunctionName() + ".<lambda>", arity, capTypes, sam) { _, args, capLocals, body ->
        for ((i, v) in caps.withIndex()) locals[v] = capLocals[i]
        currentFunction = fn
        currentReturn = if (sam != null) sam.ret else if (ret == TUnit) TUnit else anyNullable
        unitAsNull = sam == null
        for ((i, p) in fn.parameters.withIndex()) {
            val t = mirType(p.type, p)
            val l = MirLocal(localCounter++, p.name.ifEmpty { "p$i" }, t)
            body += MirStmt.Declare(l, convertFromErased(MirExpr.Local(args[i]), t, p, body))
            locals[p] = l
        }
        convertBodyOf(fn, currentReturn, body)
        if (body.lastOrNull() !is MirStmt.Return) {
            body += if (sam == null) MirStmt.Return(MirExpr.NullConst(anyNullable))
            else if (sam.ret == TUnit) MirStmt.Return(null) else MirStmt.Return(MirExpr.Unreachable(sam.ret))
        }
    }
    val values = caps.map { MirExpr.Local(localOf(it, e)) }
    return MirExpr.New(ctor, values, type)
}

internal fun Ir2Mir.currentFunctionName(): String = currentFunction?.name ?: "<module>"

/** Converts an erased value (`Any?`) to the type [t] of a typed local (unboxing / unchecked cast). */
internal fun Ir2Mir.convertFromErased(v: MirExpr, t: MirType, at: IrElement, out: MutableList<MirStmt>): MirExpr {
    if (v.type == t) return v
    if (t.isPrimitive) return MirExpr.Unbox(MirExpr.Cast(v, TBoxed(t), MirExpr.CastMode.Unchecked), t)
    if (t.isRef && v.type.isRef) return MirExpr.Cast(v, t, MirExpr.CastMode.Unchecked)
    return convertTo(v, t, at)
}

/**
 * Adapts the result of a call whose declared (erased) result type differs from the type the
 * call expression has after type-argument substitution: unboxes / retypes.
 */
internal fun Ir2Mir.adaptResult(e: MirExpr, expected: MirType, at: IrElement, out: MutableList<MirStmt>): MirExpr {
    if (e.type == expected || expected == TUnit || expected == TNothing || e.type == TNothing || e.type == TUnit) return e
    if (!e.type.isRef) return e
    var v = e
    if (v.isOwned() || (v is MirExpr.FieldGet && v.type.isRef)) v = tmpOf(v, out)
    if (expected.isPrimitive) return MirExpr.Unbox(MirExpr.Cast(v, TBoxed(expected), MirExpr.CastMode.Unchecked), expected)
    if (expected.isRef) return MirExpr.Cast(v, expected, MirExpr.CastMode.Unchecked)
    return e
}

// ---- invoking function values ----------------------------------------------------------------------------

internal fun Ir2Mir.isFunctionInvoke(owner: IrSimpleFunction): Boolean {
    if (owner.name != "invoke") return false
    val p = owner.parent as? IrClass ?: return false
    val n = p.kotlinFqName
    return n.startsWith("kotlin.Function") || n.startsWith(REFLECT_PKG + ".KFunction")
}

internal fun Ir2Mir.invokeFunctionValue(c: IrCall, out: MutableList<MirStmt>): MirExpr {
    val argsIr = c.arguments.map { it ?: unsupported(c, "invoke with omitted argument") }
    inlineLambdaOf(argsIr[0])?.let { lam ->
        val rest = operands(argsIr.drop(1), out)
        val r = inlineLambdaCall(lam, rest, c, out)
        val expected = mirType(c.type, c)
        return if (expected == TUnit || expected == TNothing || r.type == TUnit) r else coerceFlexible(r, expected, c, out)
    }
    val vals = operands(argsIr, out)
    val recvType = vals[0].type
    val arity = vals.size - 1
    val recv = if (recvType is TObject && recvType.isInterface) vals[0] else MirExpr.Cast(vals[0], functionInterface(arity), MirExpr.CastMode.Unchecked)
    val iface = functionInterface(arity)
    val args = vals.drop(1).map { coerceOperand(it, anyNullable, c, out) }
    val call = MirExpr.ICall(iface.cName, 0, recv, args, invokeArgTypes(arity), anyNullable)
    val expected = mirType(c.type, c)
    if (expected == TUnit || expected == TNothing) {
        out += MirStmt.Eval(call)
        return if (expected == TUnit) MirExpr.UnitValue else MirExpr.Unreachable(TNothing)
    }
    return adaptResult(tmpOf(call, out), expected, c, out)
}

// ---- local functions ---------------------------------------------------------------------------------------

/** Registers and converts a local function (lambda-lifted). Emits nothing at the declaration site. */
internal fun Ir2Mir.liftLocalFunction(f: IrSimpleFunction) {
    if (f in liftedFns) return
    val caps = closure.capturesOf(f)
    val n = lambdaCounter++
    val outerName = currentFunctionName()
    val paramTypes = f.parameters.map { mirType(it.type, it) }
    val capTypes = caps.map { capturedType(it) }
    val cName = Mangling.function("", "$outerName\$${f.name}\$$n", capTypes + paramTypes)
    liftedFns[f] = LiftedFn(cName, caps)
    val fn = inFreshFunction {
        currentFunction = f
        val ret = mirType(f.returnType, f)
        currentReturn = ret
        unitAsNull = false
        val params = ArrayList<MirLocal>()
        for ((i, v) in caps.withIndex()) {
            val l = MirLocal(localCounter++, v.name(), capTypes[i])
            params += l
            locals[v] = l
        }
        for (p in f.parameters) {
            val l = MirLocal(localCounter++, p.name, mirType(p.type, p))
            params += l
            locals[p] = l
        }
        val out = ArrayList<MirStmt>()
        convertBodyOf(f, ret, out)
        MirFunction("$outerName.${f.name}", cName, params, ret, out)
    }
    extraFunctions += fn
}

private fun IrValueDeclaration.name(): String = when (this) {
    is IrVariable -> name
    is IrValueParameter -> name
    else -> "v"
}

/** Extra leading arguments of a call to a lifted local function: the captured values of the current context. */
internal fun Ir2Mir.liftedArgs(l: LiftedFn, at: IrElement): List<MirExpr> =
    l.captured.map { MirExpr.Local(localOf(it, at)) }

// ---- function references -----------------------------------------------------------------------------------

internal fun Ir2Mir.functionReference(e: IrFunctionReference, out: MutableList<MirStmt>): MirExpr {
    val target = e.target
    val params = target.parameters
    val given = e.arguments
    // evaluate bound arguments now (in order); unbound parameters become invoke arguments
    val boundIdx = params.indices.filter { given.getOrNull(it) != null }
    val bound = operands(boundIdx.map { given[it]!! }, out)
    val liftedCaps: List<IrValueDeclaration> = if (target is IrSimpleFunction) {
        if (target.origin == "LOCAL_FUNCTION" || target.origin == "LOCAL_FUNCTION_FOR_LAMBDA") {
            liftLocalFunction(target)
            liftedFns[target]!!.captured
        } else emptyList()
    } else emptyList()
    val boundTypes = boundIdx.map { mirType(params[it].type, params[it]) }
    // the closure captures the bound values and the captured values of a lifted local function
    val capTypes = boundTypes + liftedCaps.map { capturedType(it) }
    val arity = params.size - boundIdx.size
    val name = target.name
    val (ctor, type) = closureClass(currentFunctionName() + ".::" + name, arity, capTypes) { _, args, capLocals, body ->
        val actual = ArrayList<MirExpr>()
        var k = 0
        for ((i, p) in params.withIndex()) {
            val bi = boundIdx.indexOf(i)
            if (bi >= 0) actual += MirExpr.Local(capLocals[bi])
            else {
                val t = mirType(p.type, p)
                actual += convertFromErased(MirExpr.Local(args[k++]), t, p, body)
            }
        }
        val lifted = if (liftedCaps.isEmpty()) emptyList() else {
            liftedCaps.indices.map { MirExpr.Local(capLocals[boundIdx.size + it]) }
        }
        val callExpr = callResolved(target, lifted + actual, e, body)
        val rt = if (target is IrConstructor) typeOf(target.parent as IrClass) else mirType(target.returnType, target)
        if (rt == TUnit) {
            body += MirStmt.Eval(callExpr)
            body += MirStmt.Return(MirExpr.NullConst(anyNullable))
        } else {
            val v = if (callExpr.isOwned()) tmpOf(callExpr, body) else callExpr
            body += MirStmt.Return(convertTo(v, anyNullable, e))
        }
    }
    val values = bound + liftedCaps.map { MirExpr.Local(localOf(it, e)) }
    return MirExpr.New(ctor, values, type)
}

/** Direct call of [target] with already lowered [args] (receiver first), as used by function references. */
internal fun Ir2Mir.callResolved(target: IrFunction, args: List<MirExpr>, at: IrElement, out: MutableList<MirStmt>): MirExpr {
    if (target is IrConstructor) {
        val cName = functionNames[target] ?: unsupported(at, "reference to constructor of '${(target.parent as IrClass).kotlinFqName}'")
        return MirExpr.New(cName, args, typeOf(target.parent as IrClass))
    }
    target as IrSimpleFunction
    val liftedFn = liftedFns[target]
    if (liftedFn != null) {
        return MirExpr.Call(liftedFn.cName, args, mirType(target.returnType, target))
    }
    val parent = target.parent
    if (parent is IrClass) {
        if (parent !in classInfos) unsupported(at, "reference to '${parent.kotlinFqName}.${target.name}'")
        return memberDispatch(target, false, args, at, out)
    }
    val cName = functionNames[target] ?: unsupported(at, "reference to function '${target.name}'")
    return MirExpr.Call(cName, args, mirType(target.returnType, target))
}

// ---- SAM conversion (fun interface) ---------------------------------------------------------------------------

/** The single abstract method of a `fun interface` and its erased signature. */
internal class SamTarget(val iface: IrClass, val method: IrSimpleFunction, val argTypes: List<MirType>, val ret: MirType)

internal fun Ir2Mir.samTarget(iface: IrClass, at: IrElement): SamTarget {
    if (iface !in classInfos) unsupported(at, "SAM conversion to '${iface.name}'")
    val abstract = interfaceMethods(iface).filter { it.modality == IrModality.ABSTRACT }
    val m = abstract.singleOrNull() ?: unsupported(at, "SAM conversion to '${iface.name}' (needs exactly one abstract method)")
    val args = m.parameters.drop(1).map { mirType(it.type, it) }
    return SamTarget(iface, m, args, mirType(m.returnType, m))
}

/** `F { ... }` / a lambda or function value converted to the fun interface [e.typeOperand]. */
internal fun Ir2Mir.samValue(e: IrTypeOperatorCall, out: MutableList<MirStmt>): MirExpr {
    val iface = e.typeOperand.classOrNull ?: unsupported(e, "SAM conversion")
    val sam = samTarget(iface, e)
    var arg: IrExpression = e.argument
    while (arg is IrTypeOperatorCall && arg.operator == IrTypeOperator.IMPLICIT_CAST) arg = arg.argument
    if (arg is IrFunctionExpression) return lambdaValue(arg, out, sam)
    // any other function value: a closure that holds it and calls invoke
    val fv = operands(listOf(arg), out)[0]
    val arity = sam.argTypes.size
    val fType = functionInterface(arity)
    val (ctor, type) = closureClass(currentFunctionName() + ".<sam>", arity, listOf(fType), sam) { _, args, caps, body ->
        val boxed = args.map { coerceFlexible(MirExpr.Local(it), anyNullable, e, body) }
        val call = tmpOf(MirExpr.ICall(fType.cName, 0, MirExpr.Local(caps[0]), boxed, invokeArgTypes(arity), anyNullable), body)
        body += if (sam.ret == TUnit) MirStmt.Return(null) else MirStmt.Return(coerceFlexible(call, sam.ret, e, body))
    }
    return MirExpr.New(ctor, listOf(MirExpr.Cast(fv, fType, MirExpr.CastMode.Unchecked)), type)
}
