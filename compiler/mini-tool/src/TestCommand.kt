package mini.tool

import mini.frontend.FunDecl
import mini.frontend.UserType
import mini.frontend.parseKotlin

class TestCase(
    /** `tests/math.kt::adds`: unique, shown to the user and passed to the runner binary. */
    val id: String,
    val qualified: String,
    val file: String,
    val line: Int,
    val ignored: Boolean,
)

/** The `kotlin.test` subset that every test build gets: valid Kotlin, so the same tests also run on the JVM. */
object TestShim {
    /** Declaration-only (passed as `--extra-src`: minic does not translate annotation classes). */
    const val ANNOTATIONS = """// generated by mini: the kotlin.test annotations (declarations only)
package kotlin.test

@Target(AnnotationTarget.FUNCTION)
annotation class Test

@Target(AnnotationTarget.FUNCTION)
annotation class Ignore
"""

    const val SOURCE = """// generated by mini: the kotlin.test API subset used by `mini test`
package kotlin.test

fun formatAssertMessage(message: String?, text: String): String = if (message == null) text else message + ". " + text

fun fail(message: String? = null): Nothing = throw AssertionError(message)

fun assertTrue(actual: Boolean, message: String? = null) {
    if (!actual) throw AssertionError(formatAssertMessage(message, "Expected the value to be true."))
}

fun assertFalse(actual: Boolean, message: String? = null) {
    if (actual) throw AssertionError(formatAssertMessage(message, "Expected the value to be false."))
}

fun <T> assertEquals(expected: T, actual: T, message: String? = null) {
    if (expected != actual) throw AssertionError(formatAssertMessage(message, "Expected <" + expected + ">, actual <" + actual + ">."))
}

fun <T> assertNotEquals(illegal: T, actual: T, message: String? = null) {
    if (illegal == actual) throw AssertionError(formatAssertMessage(message, "Illegal value: <" + actual + ">."))
}

fun <T> assertSame(expected: T, actual: T, message: String? = null) {
    if (expected !== actual) throw AssertionError(formatAssertMessage(message, "Expected <" + expected + ">, actual <" + actual + "> are not the same instance."))
}

fun assertNull(actual: Any?, message: String? = null) {
    if (actual != null) throw AssertionError(formatAssertMessage(message, "Expected value to be null, but was: <" + actual + ">."))
}

fun <T : Any> assertNotNull(actual: T?, message: String? = null): T {
    if (actual == null) throw AssertionError(formatAssertMessage(message, "Expected value to be not null."))
    return actual
}

fun assertFails(block: () -> Unit): Throwable {
    try {
        block()
    } catch (e: Throwable) {
        return e
    }
    throw AssertionError("Expected an exception to be thrown, but was completed successfully.")
}

inline fun <reified T : Throwable> assertFailsWith(message: String? = null, block: () -> Unit): T {
    try {
        block()
    } catch (e: Throwable) {
        if (e is T) return e
        throw AssertionError(formatAssertMessage(message, "Expected an exception of the requested type, but was: " + e))
    }
    throw AssertionError(formatAssertMessage(message, "Expected an exception to be thrown, but was completed successfully."))
}
"""
}

object TestDiscovery {
    private fun lineOf(text: String, offset: Int): Int {
        var n = 1
        for (i in 0 until minOf(offset, text.length)) if (text[i] == '\n') n++
        return n
    }

    private fun annotationNames(m: mini.frontend.Modifiers?): List<String> =
        m?.annotations()?.mapNotNull { (it.type as? UserType)?.segments?.lastOrNull()?.name } ?: emptyList()

    /** Top-level `@Test fun name()` functions of [files] (all must belong to [pkg]). Throws [MiniError] for a test file without the import. */
    fun discover(pkg: Package, files: List<SourceFile>): List<TestCase> {
        val out = ArrayList<TestCase>()
        for (f in files) {
            if (!f.text.contains("Test")) continue
            val r = parseKotlin(f.text)
            val needsImport = ArrayList<Pair<String, Int>>()
            for (d in r.file.declarations) {
                if (d !is FunDecl || d.name == null) continue
                val names = annotationNames(d.mods)
                if ("Test" !in names) continue
                // the line of `fun name` (the annotation may be on the line above)
                val funAt = indexOfWordFun(f.text, d.start).let { if (it < 0) d.start else it }
                val line = lineOf(f.text, funAt)
                if (d.receiver != null || d.params.isNotEmpty()) {
                    throw MiniError("${f.display}:$line: test function `${d.name}` must take no parameters and have no receiver", "write `@Test fun ${d.name}() { ... }`")
                }
                if (d.mods?.has("private") == true) {
                    throw MiniError("${f.display}:$line: test function `${d.name}` is private", "tests are called by the generated runner: remove `private`")
                }
                if (r.file.imports.none { it.path.startsWith("kotlin.test") } && r.file.packageName != "kotlin.test") needsImport += Pair(d.name!!, line)
                val fn = d.name!!.trimChars('`')
                val q = (r.file.packageName?.split('.')?.map { "`$it`" } ?: emptyList()) + "`$fn`"
                val rel = Paths.relativize(pkg.dir, f.real)
                out += TestCase("$rel::$fn", q.joinToString("."), rel, line, "Ignore" in names)
            }
            if (needsImport.isNotEmpty()) {
                val (n, l) = needsImport.first()
                throw MiniError("${f.display}:$l: `@Test` on `$n` needs an import", "add `import kotlin.test.*` (or `import kotlin.test.Test`) at the top of ${f.display}")
            }
        }
        return out
    }

    fun runnerSource(tests: List<TestCase>): String {
        val sb = StringBuilder("// generated by `mini test`: runs the test named by the first argument\n")
        sb.append("fun main(args: Array<String>) {\n")
        sb.append("    val name = if (args.size > 0) args[0] else \"\"\n")
        sb.append("    when (name) {\n")
        for (t in tests) sb.append("        \"").append(t.id.replace("\\", "\\\\").replace("\"", "\\\"").replace("$", "\\$")).append("\" -> ").append(t.qualified).append("()\n")
        sb.append("        else -> throw IllegalStateException(\"mini test: no such test: \" + name)\n")
        sb.append("    }\n}\n")
        return sb.toString()
    }
}

/** Result of one test process. */
class TestOutcome(val test: TestCase, val passed: Boolean, val millis: Long, val stdout: String, val failure: String)

class TestRunner(val p: Platform, val c: Console, val builder: Builder) {

    private fun describeFailure(r: ExecResult): String {
        val err = r.stderr.lines().filter { !Diagnostics.isNoise(it) }.joinToString("\n").trim()
        val cleaned = err.replace("Exception in thread \"main\" ", "").let { stripPackagePrefixes(it) }
        if (r.startError != null) return "could not start the test binary: ${r.startError}"
        if (r.exitCode == 1 || r.exitCode == 0) return cleaned.ifEmpty { "the test failed (exit code ${r.exitCode})" }
        val sig = when (r.exitCode) { 134 -> "SIGABRT (a panic or failed internal check)"; 139 -> "SIGSEGV (crash)"; 136 -> "SIGFPE"; 137 -> "killed (SIGKILL)"; else -> null }
        val head = if (sig != null) "the test process crashed with $sig" else "the test process exited with code ${r.exitCode}"
        return if (cleaned.isEmpty()) head else "$head\n$cleaned"
    }

    /** Builds the test binary and runs the matching tests. Returns the exit code. */
    fun run(pkg: Package, filter: String?, list: Boolean, nocapture: Boolean, failFast: Boolean, passArgs: List<String>): Int {
        val o = builder.o
        val files = builder.gather(pkg, tests = true)
        val own = files.filter { it.pkg === pkg && (it.real.startsWith(pkg.testDir() + "/") || it.real.startsWith(pkg.sourceDir() + "/")) }
        val all = TestDiscovery.discover(pkg, own)
        val selected = all.filter { filter == null || it.id.contains(filter) }
        if (list) {
            for (t in selected) c.println(t.id + if (t.ignored) " (ignored)" else "")
            c.eprintln("${selected.size} test${if (selected.size == 1) "" else "s"}")
            return 0
        }
        if (all.isEmpty()) {
            c.warn("no tests found in `${pkg.name}`", "write `@Test fun name() { ... }` functions (with `import kotlin.test.*`) in tests/*.kt")
            return 0
        }
        val dir = Paths.join(builder.project.buildDir, "test", pkg.name)
        val shim = Paths.join(dir, "kotlin_test.kt")
        val annotations = Paths.join(dir, "kotlin_test_annotations.kt")
        val runnerMain = Paths.join(dir, "runner_main.kt")
        p.mkdirs(dir)
        p.writeText(shim, TestShim.SOURCE)
        p.writeText(annotations, TestShim.ANNOTATIONS)
        p.writeText(runnerMain, TestDiscovery.runnerSource(all))
        val binary = Paths.join(dir, "runner")
        c.status("Compiling", "${pkg.id} (tests)")
        val b = builder.compileSet(pkg, files, listOf(shim, runnerMain), listOf(annotations), binary, Paths.join(dir, ".fingerprint"), "test")
        if (!b.success) return 1
        if (b.fresh) c.status("Fresh", "test binary (no changes)") else c.status("Finished", "test build in ${formatDuration(b.millis)}")
        if (selected.isEmpty()) {
            c.warn("no test matches `$filter`", "list them with `mini test --list`")
            return 0
        }
        c.status("Running", "${selected.size} test${if (selected.size == 1) "" else "s"} (${builder.display(binary)})")
        c.eprintln()
        val s = c.out
        val outcomes = ArrayList<TestOutcome>()
        var ignored = 0
        val t0 = p.nowMillis()
        for (t in selected) {
            if (t.ignored) {
                ignored++
                c.println("test ${t.id} ... ${s.yellow("ignored")}")
                continue
            }
            val start = p.nowMillis()
            val r = p.exec(Exec(listOf(binary, t.id) + passArgs, cwd = pkg.dir))
            val ms = p.nowMillis() - start
            val ok = r.exitCode == 0 && r.startError == null
            val oc = TestOutcome(t, ok, ms, r.stdout, if (ok) "" else describeFailure(r))
            outcomes += oc
            c.println("test ${t.id} ... ${if (ok) s.green("ok") else s.red("FAILED", true)} ${s.dim("(${formatDuration(ms)})")}")
            if (ok && nocapture && r.stdout.isNotEmpty()) c.print(r.stdout.let { if (it.endsWith("\n")) it else it + "\n" })
            if (!ok && failFast) break
        }
        val failures = outcomes.filter { !it.passed }
        if (failures.isNotEmpty()) {
            c.println()
            c.println("failures:")
            for (f in failures) {
                c.println()
                c.println(s.red("---- ${f.test.id} (${f.test.file}:${f.test.line}) ----", true))
                if (f.stdout.isNotBlank()) { c.println("stdout:"); c.print(f.stdout.let { if (it.endsWith("\n")) it else it + "\n" }) }
                c.println(f.failure)
            }
            c.println()
            c.println("failures:")
            for (f in failures) c.println("    ${f.test.id}")
        }
        c.println()
        val passed = outcomes.count { it.passed }
        val head = if (failures.isEmpty()) s.green("ok", true) else s.red("FAILED", true)
        c.println("test result: $head. $passed passed; ${failures.size} failed; $ignored ignored; finished in ${formatDuration(p.nowMillis() - t0)}")
        if (failures.isNotEmpty()) {
            c.eprintln()
            c.error("test failed in `${pkg.name}`: ${failures.size} of ${passed + failures.size} tests failed", "re-run one with `mini test ${failures.first().test.id.substringAfterLast("::")}`")
        }
        return if (failures.isEmpty()) 0 else 1
    }
}
