package mini.tool

/** A problem the user can fix: printed as `error: <message>` plus `help:` lines, no stack trace. */
class MiniError(val msg: String, val help: String? = null, val rendered: String? = null, val exitCode: Int = 1) : Exception(msg)

fun miniHome(p: Platform): String =
    p.env("MINI_HOME")?.takeIf { it.isNotEmpty() } ?: Paths.join(p.homeDir() ?: "/tmp", ".mini")

/** One entry of `mini.lock`. */
class LockEntry(val url: String, val spec: String, val commit: String)

/** `mini.lock`: pins git dependencies to exact commits so that builds are reproducible. */
class Lockfile(val git: Map<String, LockEntry> = emptyMap()) {
    fun render(): String {
        val sb = StringBuilder()
        sb.append("# This file is generated by `mini`. It pins git dependencies to exact commits.\n")
        sb.append("# Do not edit it by hand; run `mini update` to move the pins.\n")
        sb.append("version = 1\n")
        for (name in git.keys.sorted()) {
            val e = git.getValue(name)
            sb.append("\n[git.$name]\n")
            sb.append("url = ${quote(e.url)}\n")
            sb.append("spec = ${quote(e.spec)}\n")
            sb.append("commit = ${quote(e.commit)}\n")
        }
        return sb.toString()
    }

    fun sameAs(o: Lockfile): Boolean = render() == o.render()

    companion object {
        private fun quote(s: String) = "\"" + s.replace("\\", "\\\\").replace("\"", "\\\"") + "\""

        /** Lenient: a damaged or foreign lock file is treated as empty (it will be rewritten). */
        fun parse(text: String): Lockfile = try {
            val root = parseToml(text)
            val out = LinkedHashMap<String, LockEntry>()
            val g = root["git"] as? TTable
            if (g != null) for ((name, e) in g.entries) {
                val t = e.value as? TTable ?: continue
                val url = (t["url"] as? TStr)?.value ?: continue
                val spec = (t["spec"] as? TStr)?.value ?: continue
                val commit = (t["commit"] as? TStr)?.value ?: continue
                out[name] = LockEntry(url, spec, commit)
            }
            Lockfile(out)
        } catch (e: TomlError) {
            Lockfile()
        }
    }
}

/**
 * Git dependencies live in `$MINI_HOME/git` (default `~/.mini/git`): a mirror clone per URL (`db/`) and one
 * immutable checkout per commit (`checkouts/`). A commit that is already checked out needs no network at all.
 */
class GitCache(val p: Platform, val c: Console, val home: String, val offline: Boolean) {
    private val root = Paths.join(home, "git")

    private fun slug(url: String): String {
        val last = url.trimEndChars('/').substringAfterLast('/').substringAfterLast(':').removeSuffix(".git")
        return ManifestParser.sanitizeName(last) + "-" + Hasher.of(url).substring(0, 12)
    }

    fun dbDir(url: String) = Paths.join(root, "db", slug(url))
    fun checkoutDir(url: String, commit: String) = Paths.join(root, "checkouts", slug(url), commit.take(12))

    private fun git(args: List<String>, cwd: String? = null): ExecResult {
        val cmd = listOf("git") + args
        c.trace(cmd.joinToString(" "))
        return p.exec(Exec(cmd, cwd, mapOf("GIT_TERMINAL_PROMPT" to "0", "GIT_ASKPASS" to "true", "LC_ALL" to "C")))
    }

    private fun requireGit() {
        val r = p.exec(Exec(listOf("git", "--version")))
        if (r.exitCode != 0) {
            throw MiniError("`git` is needed for git dependencies but was not found", "install git (e.g. `sudo apt install git` or `brew install git`) and run `mini doctor`")
        }
    }

    private fun fail(url: String, what: String, r: ExecResult): Nothing {
        val detail = (r.stderr.ifBlank { r.stdout }).trim().lines().take(6).joinToString("\n         ")
        throw MiniError(
            "$what for git dependency `$url` failed" + if (detail.isNotEmpty()) ":\n         $detail" else "",
            "check the URL, your network connection and your git credentials; use `--offline` to use only cached repositories",
        )
    }

    /** Clones or updates the mirror of [url]. */
    private fun fetch(url: String, cloneUrl: String) {
        if (offline) throw MiniError("git repository `$url` is not in the local cache and `--offline` was given", "run once without `--offline` to download it")
        requireGit()
        val db = dbDir(url)
        if (p.isDirectory(db)) {
            c.status("Updating", "git repository `$url`")
            val r = git(listOf("-C", db, "remote", "update", "--prune"))
            if (r.exitCode != 0) fail(url, "updating", r)
        } else {
            c.status("Cloning", "git repository `$url`")
            p.mkdirs(Paths.parent(db)!!)
            val r = git(listOf("clone", "--mirror", "--quiet", cloneUrl, db))
            if (r.exitCode != 0) { p.remove(db); fail(url, "cloning", r) }
        }
    }

    private fun revParse(db: String, expr: String): String? {
        val r = git(listOf("-C", db, "rev-parse", "--verify", "--quiet", "$expr^{commit}"))
        return if (r.exitCode == 0) r.stdout.trim().takeIf { it.length >= 40 } else null
    }

    /** The commit that [ref] currently selects, fetching when needed. [cloneUrl] is [url] with local paths made absolute. */
    fun resolve(url: String, cloneUrl: String, ref: GitRef, refresh: Boolean): String {
        var fetched = false
        if (!p.isDirectory(dbDir(url)) || (refresh && !offline && ref !is GitRef.Rev)) {
            fetch(url, cloneUrl); fetched = true
        }
        val db = dbDir(url)
        fun lookup(): String? = when (ref) {
            is GitRef.Default -> revParse(db, "HEAD")
            is GitRef.Tag -> revParse(db, "refs/tags/${ref.name}")
            is GitRef.Branch -> revParse(db, "refs/heads/${ref.name}")
            is GitRef.Rev -> revParse(db, ref.rev)
        }
        var commit = lookup()
        if (commit == null && !fetched && !offline) { fetch(url, cloneUrl); commit = lookup() }
        if (commit != null) return commit
        val what = when (ref) {
            is GitRef.Default -> "the default branch"
            is GitRef.Tag -> "tag `${ref.name}`"
            is GitRef.Branch -> "branch `${ref.name}`"
            is GitRef.Rev -> "revision `${ref.rev}`"
        }
        val tags = git(listOf("-C", db, "tag", "--list")).stdout.lines().filter { it.isNotBlank() }
        val hint = if (ref is GitRef.Tag) suggest(ref.name, tags)?.let { "did you mean tag `$it`?" } else null
        throw MiniError("git repository `$url` has no $what", hint ?: if (offline) "the cache may be out of date; run without `--offline`" else "check the spelling in mini.toml")
    }

    /** Directory with the sources of [commit]; creates the checkout on first use. */
    fun checkout(url: String, cloneUrl: String, commit: String): String {
        val dir = checkoutDir(url, commit)
        val marker = Paths.join(dir, ".mini-checkout")
        if (p.exists(marker)) return dir
        val db = dbDir(url)
        if (!p.isDirectory(db) || revParse(db, commit) == null) fetch(url, cloneUrl)
        if (revParse(db, commit) == null) {
            throw MiniError("commit $commit of `$url` is not available", "the repository may have been rewritten; run `mini update`")
        }
        requireGit()
        p.remove(dir)
        p.mkdirs(Paths.parent(dir)!!)
        var r = git(listOf("clone", "--quiet", "--no-checkout", db, dir))
        if (r.exitCode != 0) { p.remove(dir); fail(url, "checking out", r) }
        r = git(listOf("-C", dir, "-c", "advice.detachedHead=false", "checkout", "--quiet", "--detach", commit))
        if (r.exitCode != 0) { p.remove(dir); fail(url, "checking out", r) }
        p.writeText(marker, commit + "\n")
        return dir
    }
}
