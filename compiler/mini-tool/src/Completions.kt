package mini.tool

/** Shell completion scripts, generated from the command table so they never go stale. */
object Completions {
    val shells = listOf("bash", "zsh", "fish")

    private fun flagWords(c: Command): List<String> =
        (c.flags + CommandLine.global).map { if (it.long == "Werror") "-Werror" else "--${it.long}" }

    private fun valueFiles(f: Flag) = f.long == "manifest-path" || f.long == "path"

    fun generate(shell: String): String = when (shell) {
        "bash" -> bash()
        "zsh" -> zsh()
        "fish" -> fish()
        else -> throw UsageError("unknown shell `$shell`", suggest(shell, shells)?.let { "did you mean `$it`?" } ?: "supported: bash, zsh, fish")
    }

    private fun bash(): String {
        val cmds = CommandLine.commands.joinToString(" ") { it.name }
        val sb = StringBuilder()
        sb.append("# bash completion for mini (generated by `mini completions bash`)\n")
        sb.append("_mini() {\n")
        sb.append("    local cur prev cmd opts\n")
        sb.append("    COMPREPLY=()\n")
        sb.append("    cur=\"\${COMP_WORDS[COMP_CWORD]}\"\n")
        sb.append("    prev=\"\${COMP_WORDS[COMP_CWORD-1]}\"\n")
        sb.append("    cmd=\"\"\n")
        sb.append("    local i\n")
        sb.append("    for ((i=1; i<COMP_CWORD; i++)); do\n")
        sb.append("        case \"\${COMP_WORDS[i]}\" in -*) ;; *) cmd=\"\${COMP_WORDS[i]}\"; break ;; esac\n")
        sb.append("    done\n")
        sb.append("    case \"\$prev\" in\n")
        sb.append("        --color) COMPREPLY=( \$(compgen -W \"auto always never\" -- \"\$cur\") ); return ;;\n")
        sb.append("        --message-format) COMPREPLY=( \$(compgen -W \"human json\" -- \"\$cur\") ); return ;;\n")
        sb.append("        --path|--manifest-path) COMPREPLY=( \$(compgen -f -- \"\$cur\") ); return ;;\n")
        sb.append("    esac\n")
        sb.append("    if [ -z \"\$cmd\" ]; then\n")
        sb.append("        COMPREPLY=( \$(compgen -W \"$cmds --help --version\" -- \"\$cur\") )\n")
        sb.append("        return\n")
        sb.append("    fi\n")
        sb.append("    case \"\$cmd\" in\n")
        for (c in CommandLine.commands) {
            val extra = when (c.name) {
                "help" -> " " + CommandLine.commands.joinToString(" ") { it.name }
                "completions" -> " bash zsh fish"
                "explain" -> " " + Explain.codes().joinToString(" ")
                else -> ""
            }
            val words = if (c.name == "help" || c.name == "completions" || c.name == "explain") extra.trim() + " " + flagWords(c).joinToString(" ") else flagWords(c).joinToString(" ")
            sb.append("        ${c.name}) opts=\"$words\" ;;\n")
        }
        sb.append("        *) opts=\"\" ;;\n")
        sb.append("    esac\n")
        sb.append("    COMPREPLY=( \$(compgen -W \"\$opts\" -- \"\$cur\") )\n")
        sb.append("}\n")
        sb.append("complete -F _mini mini\n")
        return sb.toString()
    }

    private fun zshEscape(s: String) = s.replace("'", "'\\''").replace("[", "\\[").replace("]", "\\]").replace(":", "\\:")

    private fun zsh(): String {
        val sb = StringBuilder()
        sb.append("#compdef mini\n# zsh completion for mini (generated by `mini completions zsh`)\n\n")
        sb.append("_mini() {\n    local curcontext=\"\$curcontext\" state line\n    typeset -A opt_args\n")
        sb.append("    local -a commands\n    commands=(\n")
        for (c in CommandLine.commands) sb.append("        '${c.name}:${zshEscape(c.summary)}'\n")
        sb.append("    )\n")
        sb.append("    _arguments -C \\\n")
        for (g in CommandLine.global) sb.append("        '--${g.long}[${zshEscape(g.help)}]${if (g.choices != null) ":when:(" + g.choices.joinToString(" ") + ")" else ""}' \\\n")
        sb.append("        '1: :->command' \\\n        '*:: :->args'\n")
        sb.append("    case \$state in\n        command) _describe 'mini command' commands ;;\n        args)\n            case \$words[1] in\n")
        for (c in CommandLine.commands) {
            sb.append("                ${c.name})\n                    _arguments \\\n")
            for (f in c.flags) {
                val dash = if (f.long == "Werror") "-Werror" else "--${f.long}"
                val spec = when {
                    f.choices != null -> ":${f.long}:(${f.choices.joinToString(" ")})"
                    valueFiles(f) -> ":path:_files"
                    f.value != null -> ":${f.long}:"
                    else -> ""
                }
                sb.append("                        '$dash[${zshEscape(f.help)}]$spec' \\\n")
            }
            val positional = when (c.name) {
                "completions" -> "'1:shell:(bash zsh fish)'"
                "help" -> "'1:command:(${CommandLine.commands.joinToString(" ") { it.name }})'"
                "explain" -> "'1:code:(${Explain.codes().joinToString(" ")})'"
                else -> "'*::arguments:'"
            }
            sb.append("                        $positional ;;\n")
        }
        sb.append("            esac ;;\n    esac\n}\n\n_mini \"\$@\"\n")
        return sb.toString()
    }

    private fun fishEscape(s: String) = s.replace("\\", "\\\\").replace("'", "\\'")

    private fun fish(): String {
        val sb = StringBuilder()
        sb.append("# fish completion for mini (generated by `mini completions fish`)\n")
        sb.append("complete -c mini -f\n")
        for (g in CommandLine.global) {
            val s = if (g.short != null) " -s ${g.short}" else ""
            val a = if (g.choices != null) " -x -a '${g.choices.joinToString(" ")}'" else ""
            sb.append("complete -c mini$s -l ${g.long}$a -d '${fishEscape(g.help)}'\n")
        }
        val names = CommandLine.commands.joinToString(" ") { it.name }
        for (c in CommandLine.commands) {
            sb.append("complete -c mini -n '__fish_use_subcommand' -a ${c.name} -d '${fishEscape(c.summary)}'\n")
            for (f in c.flags) {
                val s = if (f.short != null) " -s ${f.short}" else ""
                val long = if (f.long == "Werror") " -o Werror" else " -l ${f.long}"
                val a = when {
                    f.choices != null -> " -x -a '${f.choices.joinToString(" ")}'"
                    valueFiles(f) -> " -r -F"
                    f.value != null -> " -r"
                    else -> ""
                }
                sb.append("complete -c mini -n '__fish_seen_subcommand_from ${c.name}'$s$long$a -d '${fishEscape(f.help)}'\n")
            }
        }
        sb.append("complete -c mini -n '__fish_seen_subcommand_from help' -a '$names'\n")
        sb.append("complete -c mini -n '__fish_seen_subcommand_from completions' -a 'bash zsh fish'\n")
        sb.append("complete -c mini -n '__fish_seen_subcommand_from explain' -a '${Explain.codes().joinToString(" ")}'\n")
        return sb.toString()
    }
}
